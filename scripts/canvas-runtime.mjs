import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';
import { format, resolveConfig } from 'prettier';

const root = new URL('../', import.meta.url);
const output = new URL('src/renderers/canvas-runtime.generated.ts', root);
const check = process.argv.includes('--check');
const result = await build({
  absWorkingDir: fileURLToPath(root),
  entryPoints: ['src/canvas-runtime/main.ts'],
  bundle: true,
  format: 'iife',
  minify: true,
  target: 'es2022',
  platform: 'browser',
  legalComments: 'none',
  charset: 'ascii',
  write: false,
  metafile: true,
  logLevel: 'warning',
});
const bundle = result.outputFiles[0]?.text.trim();
if (!bundle) throw new Error('MISSING_CANVAS_RUNTIME');
// The bundle is embedded in an inline script: nothing in it may end or escape that element.
if (/<\/script|<!--/i.test(bundle)) throw new Error('UNSAFE_CANVAS_RUNTIME');
const sources = Object.keys(result.metafile.inputs)
  .map((path) => path.split('\\').join('/'))
  .filter((path) => path.startsWith('src/'))
  .sort();
const hash = createHash('sha256');
for (const path of sources) {
  const text = await readFile(new URL(path, root), 'utf8');
  hash.update(path);
  hash.update('\n');
  hash.update(text.split('\r\n').join('\n'));
  hash.update('\n');
}
const code =
  '// Generated by scripts/canvas-runtime.mjs (yarn runtime). Do not edit by hand.\n' +
  `export const CANVAS_RUNTIME_SOURCES: readonly string[] = ${JSON.stringify(sources)};\n` +
  `export const CANVAS_RUNTIME_HASH = ${JSON.stringify(hash.digest('hex'))};\n` +
  `export const CANVAS_RUNTIME_BUNDLE = ${JSON.stringify(bundle)};\n`;
const options = await resolveConfig(fileURLToPath(output));
const formatted = await format(code, { ...options, parser: 'typescript' });
if (check) {
  const current = await readFile(output, 'utf8').catch(() => '');
  if (current !== formatted) throw new Error('STALE_CANVAS_RUNTIME');
} else await writeFile(output, formatted);
