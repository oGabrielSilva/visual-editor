import type { CanvasBridgeConfiguration, CanvasBridgeRegion } from '../renderers/canvas-bridge';
import { EDIT_NODE_ATTRIBUTE as EDIT, NODE_ATTRIBUTE as NODE } from '../core/canvas-contract';
import { BridgeChannel } from './messages';

export type Placement = 'before' | 'after' | 'inside';
export interface FramePoint {
  readonly x: number;
  readonly y: number;
}

export function isRegion(value: unknown): value is CanvasBridgeRegion {
  if (!value || typeof value !== 'object') return false;
  const region = value as Record<string, unknown>;
  return (
    typeof region.id === 'string' &&
    (region.parentId === null || typeof region.parentId === 'string') &&
    typeof region.editable === 'boolean' &&
    typeof region.container === 'boolean' &&
    (region.blocks === undefined || typeof region.blocks === 'boolean') &&
    (region.links === undefined || typeof region.links === 'boolean') &&
    (region.label === undefined ||
      (typeof region.label === 'string' && region.label.length <= 80)) &&
    (region.media === undefined || region.media === 'image')
  );
}

/**
 * What every module of the runtime shares: the channel to the host, the regions of the revision
 * on screen, the selection and one measuring frame. It decides nothing about interaction.
 */
export class CanvasContext {
  readonly lifecycle = new AbortController();
  readonly channel: BridgeChannel;
  readonly marked = new Map<string, HTMLElement>();
  regions: Map<string, CanvasBridgeRegion>;
  readOnly: boolean;
  selectedId: string | undefined;
  disposed = false;
  /** A block or palette gesture is in course: hover feedback stays out of the way. */
  dragging = false;
  /** When the keyboard last asked for the menu of a block, to ignore the event the key fires. */
  keyboardMenu = -Infinity;
  #frame = 0;
  readonly #measurers: (() => void)[] = [];
  readonly #selecting: (() => void)[] = [];

  constructor(
    readonly cfg: CanvasBridgeConfiguration,
    readonly controls: HTMLElement,
  ) {
    this.channel = new BridgeChannel(cfg.nonce, cfg.revision);
    this.readOnly = cfg.readOnly;
    this.regions = new Map(cfg.regions.map((region) => [region.id, region]));
    this.index();
  }

  get signal(): AbortSignal {
    return this.lifecycle.signal;
  }

  index(): void {
    this.marked.clear();
    for (const node of document.querySelectorAll<HTMLElement>(`[${NODE}]`)) {
      const id = node.getAttribute(NODE);
      if (id && this.regions.has(id)) this.marked.set(id, node);
    }
  }

  /**
   * The element whose text is edited in place: the block itself, or the element inside it which
   * carries the edit mark of the same block (the text of an e-mail cell, generated by a block
   * piece). The host already admitted that mark only inside its own block.
   */
  textElement(id: string): HTMLElement | undefined {
    const node = this.marked.get(id);
    if (!node || node.getAttribute(EDIT) === id) return node;
    for (const inner of node.querySelectorAll<HTMLElement>(`[${EDIT}]`))
      if (inner.getAttribute(EDIT) === id && inner.closest(`[${NODE}]`) === node) return inner;
    return node;
  }

  setRegions(regions: readonly CanvasBridgeRegion[]): void {
    this.regions = new Map(regions.map((region) => [region.id, region]));
    this.index();
  }

  send(type: string, payload: Record<string, unknown> = {}): void {
    if (!this.disposed) this.channel.send(type, payload);
  }

  select(id: string | undefined): void {
    if (this.disposed || !id || !this.regions.has(id)) return;
    for (const before of this.#selecting) before();
    this.channel.selection(id);
  }

  /** Runs before this frame asks the host to select another block. */
  beforeSelect(action: () => void): void {
    this.#selecting.push(action);
  }

  regionFrom(element: Element | null): string | undefined {
    const id = element?.closest(`[${NODE}]`)?.getAttribute(NODE);
    return id && this.regions.has(id) ? id : undefined;
  }

  /** The closest selectable ancestor in the piece, whatever plain markup lies between. */
  parentOf(id: string | undefined): string | undefined {
    const element = id ? this.marked.get(id) : undefined;
    return this.regionFrom(element?.parentElement ?? null);
  }

  /** Regions which share the parent of `id`, in document order. */
  siblings(id: string): string[] {
    const parent = this.regions.get(id)?.parentId;
    const result: string[] = [];
    for (const region of this.regions.values())
      if (region.parentId === parent && this.marked.has(region.id)) result.push(region.id);
    return result;
  }

  isControls(event: Event): boolean {
    return event.composedPath().includes(this.controls);
  }

  /** Hit test of the piece itself: the trusted overlay never answers for a document element. */
  elementAt(x: number, y: number): Element | null {
    const previous = this.controls.style.getPropertyValue('visibility');
    this.controls.style.setProperty('visibility', 'hidden', 'important');
    const element = document.elementFromPoint(x, y);
    this.controls.style.setProperty('visibility', previous || 'visible', 'important');
    return element;
  }

  onMeasure(measure: () => void): void {
    this.#measurers.push(measure);
  }

  schedule(): void {
    if (this.disposed || this.#frame || document.readyState === 'loading') return;
    this.#frame = requestAnimationFrame(() => {
      this.#frame = 0;
      for (const measure of this.#measurers) measure();
    });
  }

  dispose(): void {
    this.disposed = true;
    this.lifecycle.abort();
    if (this.#frame) cancelAnimationFrame(this.#frame);
    this.#frame = 0;
    this.channel.dispose();
  }
}
